import assert from 'node:assert/strict';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequire } from 'node:module';
import { build } from 'esbuild';

// Exercise decision eligibility and render the real components without a browser host.
const directory = await mkdtemp(join(tmpdir(), 'pricing-ui-'));
try {
  const entry = `
    import { createElement } from 'react';
    import { renderToStaticMarkup } from 'react-dom/server';
    import { canReview, canBulkApprove } from './src/api/operations';
    import { GlobalControls } from './src/features/GlobalControls';
    import { RecommendationDrawer } from './src/features/RecommendationDrawer';
    import { ScenarioReport } from './src/features/ScenarioReport';
    import { DistributionBand } from './src/components/Forecast';
    import { citationIds } from './src/components/EvidenceSources';
    import { MemoryRouter } from 'react-router-dom';
    import { LoopDrawer } from './src/features/LoopDrawer';
    import { emptyRunConstraints, serializeRunConstraints } from './src/api/runConstraints';
    import { RunConstraints } from './src/components/RunConstraints';
    export { canReview, canBulkApprove, citationIds, emptyRunConstraints, serializeRunConstraints };
    export const renderControls = () => renderToStaticMarkup(createElement(GlobalControls));
    export const renderDecision = (item, peers=[item]) => renderToStaticMarkup(createElement(RecommendationDrawer, { item, peers, onClose(){}, onChanged(){} }));
    export const renderScenario = scenario => renderToStaticMarkup(createElement(ScenarioReport, { scenario }));
    export const renderBand = distribution => renderToStaticMarkup(createElement(DistributionBand, {label:'Revenue', distribution}));
    export const renderLoop = state => renderToStaticMarkup(createElement(MemoryRouter, null, createElement(LoopDrawer, {state, connected:true, onClose(){}, onChanged(){}})));
    export const renderConstraints = value => renderToStaticMarkup(createElement(RunConstraints, {categories:['Beverages','Snacks'], value, onChange(){}}));
  `;
  const bundle = await build({ stdin: { contents: entry, resolveDir: process.cwd(), loader: 'js' }, bundle: true, write: false, platform: 'node', format: 'cjs', jsx: 'automatic', logLevel: 'silent' });
  const filename = join(directory, 'checks.cjs');
  await writeFile(filename, bundle.outputFiles[0].contents);
  const require = createRequire(import.meta.url);
  const ui = require(filename);
  const item = { id: 'rec-1', run_id: 'run-1', revision: 2, sku: 'TEST-1', name: 'Test product', current_price: '10.00', proposed_price: '10.50', delta_pct: 5, confidence: 0.85, band: 'review', band_reasons: [], compliance: {status: 'passed', rules: []}, compliance_status: 'passed', stability: {}, status: 'pending_review', mode_at_decision: 'supervised', mode_version: 1, executable: false };
  assert.equal(ui.canBulkApprove(item, 0.84), true, 'A Review item above the threshold is eligible.');
  assert.equal(ui.canBulkApprove(item, 0.85), false, 'Bulk requires confidence strictly above the threshold.');
  for (const change of [{ band: 'auto_approve' }, { band: 'escalate' }, { confidence: 0.84999 }, { compliance: {status: 'failed'} }, { status: 'applied' }, { status: 'rejected' }, { status: 'unknown' }]) {
    assert.equal(ui.canBulkApprove({ ...item, ...change }, 0.85), false, `Bulk must exclude ${JSON.stringify(change)}.`);
  }
  assert.equal(ui.canReview({ ...item, status: 'escalated' }), true);
  assert.equal(ui.canReview({ ...item, status: 'blocked', compliance: {status:'failed'} }), false);
  const controls = ui.renderControls();
  assert.match(controls, /Loading mode/);
  assert.match(controls, /Loop loading/);
  assert.match(controls, /<select[^>]*aria-label="Operating mode"[^>]*disabled/);
  assert.match(controls, /<button[^>]*class="kill-button"[^>]*disabled/);
  const blocked = ui.renderDecision({ ...item, status: 'blocked', compliance: {status:'failed', rules:[{rule:'margin_floor',passed:false,actual:0.1,threshold:0.2}]} });
  assert.match(blocked, /Compliance veto/);
  assert.doesNotMatch(blocked, /Submit decision/);
  assert.doesNotMatch(blocked, /Revert this change/);
  const applied = ui.renderDecision({ ...item, status:'applied', approval:{kind:'automatic',actor:'system'} });
  assert.match(applied, /System decision/);
  assert.match(applied, /Revert this change/);
  assert.doesNotMatch(applied, /Submit decision/);
  const unchanged = ui.renderDecision({...item,status:'unchanged',execution:{status:'applied',unchanged:true}});
  assert.match(unchanged, /No change/);
  assert.doesNotMatch(unchanged, /Submit decision|Revert this change/);
  const pending = ui.renderDecision(item);
  assert.match(pending, /Submit decision/);
  const family = [{...item,id:'large',name:'Large pack',family_id:'f',product_evidence:{size:20},proposed_price:'10.00'}, {...item,id:'small',name:'Small pack',family_id:'f',product_evidence:{size:10},proposed_price:'20.00'}];
  const ladder = ui.renderDecision(family[0], family);
  assert.match(ladder, /Size 10/);
  assert.match(ladder, /Size 20/);
  assert.match(ladder, /Break/);
  const scenario = ui.renderScenario({ items:[{...item,forecast:{revenue:{mean:100,median:100,lower:80,upper:125},below_margin_floor_probability:0.03},baseline:{price:'10.25',forecast:{revenue:{mean:99}}},assumptions:['Stock capped']}],configuration:{seed:42} });
  assert.match(scenario, /95 percent interval/);
  assert.match(scenario, /3%/);
  assert.match(scenario, /Baseline/);
  assert.match(scenario, /Stock capped/);
  assert.doesNotMatch(scenario, /Submit decision/);
  const missingInterval = ui.renderBand({mean:100});
  assert.match(missingInterval, /Interval unavailable/);
  assert.deepEqual(ui.citationIds([{citations:['source-a','source-b']},{citation_id:'source-a'}]), ['source-a','source-b']);
  assert.deepEqual(ui.citationIds({citations:['source-a'],rationale:'Narrative text is not a source ID.'}), ['source-a']);
  const loop = ui.renderLoop({running:true,status:'running',iteration_count:2,iterations:[{iteration:1,run_id:'loop-run-1',status:'completed',decisions:{total:8,auto_approved:3,queued:2,applied:1,unchanged:2,unknown:1,blocked:1}},{iteration:2,run_id:'loop-run-2',status:'running'}]});
  assert.match(loop, /Auto approved/);
  assert.match(loop, /Queued/);
  assert.match(loop, /Unknown/);
  assert.match(loop, /Blocked/);
  assert.match(loop, /No change/);
  assert.match(loop, /Decision counts pending/);
  assert.match(loop, /8 recommendations/);
  assert.match(loop, /href="\/runs\?id=loop-run-2"/);
  assert.ok(loop.indexOf('href="/runs?id=loop-run-2"') < loop.indexOf('href="/runs?id=loop-run-1"'), 'Latest iteration is shown first.');
  const empty = ui.emptyRunConstraints();
  assert.equal(ui.serializeRunConstraints(empty, ['Beverages']), undefined, 'Blank controls add no run constraint.');
  assert.deepEqual(ui.serializeRunConstraints({...empty,maxChangePct:'5',categoryFloors:{Beverages:'1.2'},categoryCeilings:{Beverages:'8'}}, ['Beverages']), {max_change_pct:0.05,category_floors:{Beverages:'1.20'},category_ceilings:{Beverages:'8.00'}}, 'Human percentages become fractions and money stays decimal strings.');
  assert.deepEqual(ui.serializeRunConstraints({...empty,maxChangePct:'0'}, []), {max_change_pct:0}, 'Zero change is an explicit constraint, not an omitted value.');
  assert.deepEqual(ui.serializeRunConstraints({...empty,maxChangePct:'100'}, []), {max_change_pct:1});
  assert.equal(ui.serializeRunConstraints({...empty,categoryFloors:{Snacks:'bad'}}, ['Beverages']), undefined, 'Hidden out-of-scope bounds are not submitted.');
  assert.deepEqual(ui.serializeRunConstraints({...empty,categoryFloors:{Beverages:'2'},categoryCeilings:{Beverages:'2'}}, ['Beverages']), {category_floors:{Beverages:'2.00'},category_ceilings:{Beverages:'2.00'}}, 'An equal floor and ceiling is valid.');
  for (const percent of ['-1','100.01','Infinity','NaN','1e2']) assert.throws(() => ui.serializeRunConstraints({...empty,maxChangePct:percent}, []), /Maximum price change/);
  for (const price of ['0','-1','1.234','1e2','100000000','NaN']) assert.throws(() => ui.serializeRunConstraints({...empty,categoryFloors:{Beverages:price}}, ['Beverages']), /positive price/);
  assert.throws(() => ui.serializeRunConstraints({...empty,categoryFloors:{Beverages:'8'},categoryCeilings:{Beverages:'7.99'}}, ['Beverages']), /floor cannot exceed/);
  const constraintForm = ui.renderConstraints({...empty,maxChangePct:'5'});
  assert.match(constraintForm, /Advanced price constraints/);
  assert.match(constraintForm, /Maximum price change \(%\)/);
  assert.match(constraintForm, /Beverages/);
  assert.match(constraintForm, /Snacks/);
  assert.match(constraintForm, /No extra floor/);
  console.log('UI safety and rendering checks passed.');
} finally {
  await rm(directory, { recursive: true, force: true });
}
